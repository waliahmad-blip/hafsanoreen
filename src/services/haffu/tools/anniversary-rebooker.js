class AtelierLoyaltyEngine {
  /**
   * Determine client loyalty tier based on history
   */
  static determineTier({ isWeddingAlumni = true, pastSessionCount = 1 }) {
    if (isWeddingAlumni) {
      return LOYALTY_TIERS.PLATINUM_WEDDING_ALUMNI;
    }
    if (pastSessionCount >= 2) {
      return LOYALTY_TIERS.GOLD_MULTI_PORTRAIT;
    }
    return LOYALTY_TIERS.SILVER_FIRST_COMMISSION;
  }

  /**
   * Calculate rebooking investment ledger with Ontario 13% HST and loyalty credits
   */
  static calculateRebookingFinancials({ collectionPriceCAD = 550, loyaltyTier = LOYALTY_TIERS.PLATINUM_WEDDING_ALUMNI, giftRetailValueCAD = 150 }) {
    const base = Math.max(0, Number(collectionPriceCAD) || 550);
    const discountPercent = loyaltyTier.discountPercent || 0;
    const discountAmount = Math.round((base * (discountPercent / 100)) * 100) / 100;
    const subtotal = Math.round((base - discountAmount) * 100) / 100;
    const ontarioHst = Math.round(subtotal * 0.13 * 100) / 100;
    const grandTotal = Math.round((subtotal + ontarioHst) * 100) / 100;

    const retainer = Math.min(loyaltyTier.minRetainerCAD, grandTotal);
    const remainingBalance = Math.round((grandTotal - retainer) * 100) / 100;

    return {
      baseCollectionPriceCAD: base,
      loyaltyTierName: loyaltyTier.tierName,
      loyaltyDiscountPercent: discountPercent,
      loyaltyDiscountSavingsCAD: discountAmount,
      complimentaryGiftRetailValueCAD: giftRetailValueCAD,
      clientSavingsTotalCAD: Math.round((discountAmount + giftRetailValueCAD) * 100) / 100,
      subtotalCAD: subtotal,
      ontarioHst13CAD: ontarioHst,
      grandTotalCAD: grandTotal,
      retainerRequiredCAD: retainer,
      balanceDueOnSessionCAD: remainingBalance,
      currency: 'CAD'
    };
  }
}

