/**
 * HAFFU — Client Anniversary & Rebooking Concierge Engine
 * Part 7: Core Engine Class & Orchestrator
 */







class AnniversaryRebooker {
  static getMilestoneGifts() {
    return MilestoneIntelligence.getLegacyMilestoneGifts();
  }

  static validateParams(params) {
    if (!params || typeof params !== 'object') {
      throw new Error('AnniversaryRebooker: Execution parameters must be an object.');
    }
    if (params.weddingDate && isNaN(new Date(params.weddingDate).getTime())) {
      throw new Error('AnniversaryRebooker: weddingDate must be a valid ISO date string (YYYY-MM-DD).');
    }
    return true;
  }

  static execute(params = {}) {
    this.validateParams(params);

    const {
      clientName = 'Client',
      weddingDate = '2024-06-15',
      lastPackage = 'The Wedding Heirloom',
      referenceDate = '2026-09-23',
      hasChildren = false,
      clientNotes = '',
      collectionPriceCAD = 550,
      isWeddingAlumni = true,
      pastSessionCount = 1
    } = params;

    const originalDate = new Date(weddingDate);
    const today = new Date(referenceDate);

    // 1. Calculate elapsed years & upcoming anniversary
    let yearsElapsed = today.getFullYear() - originalDate.getFullYear();
    const nextAnniversary = new Date(originalDate);
    nextAnniversary.setFullYear(today.getFullYear());

    if (nextAnniversary < today) {
      nextAnniversary.setFullYear(today.getFullYear() + 1);
    } else {
      const hasHadThisYear = today.getMonth() > originalDate.getMonth() || 
        (today.getMonth() === originalDate.getMonth() && today.getDate() >= originalDate.getDate());
      if (!hasHadThisYear) {
        yearsElapsed = Math.max(1, yearsElapsed - 1);
      }
    }

    const diffMs = nextAnniversary.getTime() - today.getTime();
    const daysUntilNext = Math.ceil(diffMs / (1000 * 60 * 60 * 24));

    // 2. Resolve milestone data
    const milestoneData = MilestoneIntelligence.resolveMilestone(yearsElapsed);
    const milestoneTheme = `${yearsElapsed}${yearsElapsed === 1 ? 'st' : yearsElapsed === 2 ? 'nd' : yearsElapsed === 3 ? 'rd' : 'th'} Anniversary (${milestoneData.traditional})`;

    // 3. Resolve seasonal pairing
    const seasonalPairing = SeasonalHaltonPairingEngine.getSeasonalPairing(nextAnniversary);

    // 4. Resolve loyalty tier & financials
    const loyaltyTier = AtelierLoyaltyEngine.determineTier({ isWeddingAlumni, pastSessionCount });
    const financials = AtelierLoyaltyEngine.calculateRebookingFinancials({
      collectionPriceCAD,
      loyaltyTier,
      giftRetailValueCAD: milestoneData.retailValue
    });

    // 5. Render invitations across channels
    const personalizedInvitation = [
      `Dear ${clientName},`,
      '',
      `Wishing you a joyful upcoming ${yearsElapsed}-year anniversary! It feels like yesterday we were documenting your vows and golden hour portraits on ${weddingDate}.`,
      '',
      `To honor your continued journey together, we would love to invite you to celebrate with an anniversary portrait session. As an atelier couple, your session includes our traditional ${milestoneTheme} gift: ${milestoneData.atelierGiftTitle} (${milestoneData.giftDescription}).`,
      '',
      'We would be delighted to welcome you back in front of the lens.',
      '',
      'With warmest affection,',
      'Hafsa & the Atelier Team'
    ].join('\n');

    const emailHtml = AnniversaryChannelRenderer.renderHtmlEmail({
      clientName,
      yearsMarried: yearsElapsed,
      weddingDate,
      milestoneTheme,
      giftTitle: milestoneData.atelierGiftTitle,
      giftDescription: milestoneData.giftDescription
    });

    const handwrittenCard = AnniversaryChannelRenderer.renderHandwrittenCard({
      clientName,
      yearsMarried: yearsElapsed,
      milestoneTheme,
      giftTitle: milestoneData.atelierGiftTitle
    });

    const smsText = AnniversaryChannelRenderer.renderSmsInvitation({
      clientName,
      yearsMarried: yearsElapsed,
      giftTitle: milestoneData.atelierGiftTitle
    });

    const whatsAppText = AnniversaryChannelRenderer.renderWhatsAppMessage({
      clientName,
      yearsMarried: yearsElapsed,
      giftTitle: milestoneData.atelierGiftTitle,
      venue: seasonalPairing.recommendedVenue
    });

    // 6. Detect life transitions
    const lifeTransitions = MilestoneIntelligence.detectLifeTransitions({
      yearsMarried: yearsElapsed,
      hasChildren,
      clientNotes
    });

    return {
      clientName,
      weddingDate,
      yearsMarried: yearsElapsed,
      nextAnniversaryDate: nextAnniversary.toISOString().split('T')[0],
      daysUntilNextAnniversary: daysUntilNext,
      milestoneTheme,
      exclusivePerk: milestoneData.atelierGiftTitle,
      perkDetails: {
        title: milestoneData.atelierGiftTitle,
        description: milestoneData.giftDescription,
        retailValueCad: milestoneData.retailValue,
        curatedDiction: milestoneData.curatedDiction
      },
      seasonalPairing,
      financials,
      personalizedInvitation,
      previousPackage: lastPackage,
      recommendedPackages: ANNIVERSARY_SESSION_COLLECTIONS,
      cadenceStages: REBOOKING_CADENCE_STAGES,
      detectedTransitions: lifeTransitions,
      renderedOutputs: {
        emailHtml,
        handwrittenCard,
        smsText,
        whatsAppText
      }
    };
  }
}

